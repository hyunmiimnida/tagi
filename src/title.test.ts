test("제목 정리: 지우면 거의 남지 않는 제목은 그대로 두고, 두 번 해도 같다", () => {
  assert.equal(cleanTitle("💙💙"), "💙💙");
  const once = cleanTitle("★[장학금] 푸른등대 장학생 선발(~11/12목 18시)★");
  assert.equal(once, "[장학금] 푸른등대 장학생 선발");
  assert.equal(cleanTitle(once), once);
});

test("제목 정리: 정리해 저장한 제목과 새로 읽은 재게시 제목을 같은 공고로 알아본다", async () => {
  const { repostKey } = await import("./dedupe.ts");
  const raw = "(재게시) [학생상담센터] 💙또래상담사 모집 안내💙 (~9/16(수)까지)";
  assert.equal(repostKey(cleanTitle("[학생상담센터] 💙또래상담사 모집 안내💙")), repostKey(raw));
});
